<#
.SYNOPSIS
    Genera los opcodes y update fields de 1.12.1 (build 5875) a partir del codigo de vMaNGOS.

.DESCRIPTION
    Lee src/game/Server/Protocol/Opcodes_1_12_1.h y src/game/Objects/UpdateFields_1_12_1.h de vmangos-core y
    escribe engine/src/net/Opcodes.gen.{h,cpp} y engine/src/net/UpdateFields.gen.{h,cpp}. Los ficheros
    generados se commitean (compilar no necesita vmangos-core) y llevan anotados el commit de origen y la licencia
    de vMaNGOS (GNU GPL, version 2 o posterior). La carpeta de vmangos-core (https://github.com/vmangos/core):
    -VmangosDir o la variable de entorno VD_VMANGOS_DIR.
    Regla del proyecto: el protocolo sale del codigo del servidor, nunca de memoria (docs/PROTOCOL.md).

.EXAMPLE
    .\scripts\gen-protocol.ps1 -VmangosDir D:\src\vmangos-core
    $env:VD_VMANGOS_DIR = 'D:\src\vmangos-core'; .\scripts\gen-protocol.ps1
#>
param(
    [string] $VmangosDir = $env:VD_VMANGOS_DIR
)

$ErrorActionPreference = 'Stop'
if (-not $VmangosDir) { throw 'Falta la carpeta de vmangos-core: -VmangosDir <carpeta> o $env:VD_VMANGOS_DIR' }
$repo = Split-Path -Parent $PSScriptRoot
$outDir = Join-Path $repo 'engine\src\net'
$opcodesPath = Join-Path $VmangosDir 'src\game\Server\Protocol\Opcodes_1_12_1.h'
$fieldsPath = Join-Path $VmangosDir 'src\game\Objects\UpdateFields_1_12_1.h'
foreach ($p in $opcodesPath, $fieldsPath) {
    if (-not (Test-Path $p)) { throw "No existe $p (vmangos-core en otra carpeta? usa -VmangosDir o VD_VMANGOS_DIR)" }
}
$commit = (& git -C $VmangosDir rev-parse --short=7 HEAD).Trim()
if ($LASTEXITCODE -ne 0) { $commit = 'desconocido' }
New-Item -ItemType Directory -Force $outDir | Out-Null

function Write-Generated([string] $name, [string[]] $lines) {
    $text = ($lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText((Join-Path $outDir $name), $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "  $name"
}

$banner = @(
    "// Generated by scripts/gen-protocol.ps1 from vMaNGOS (https://github.com/vmangos/core) commit $commit, whose",
    '// sources are licensed under the GNU General Public License, version 2 or later. Do not edit: regenerate instead.',
    ''
)

# --- Opcodes -----------------------------------------------------------------------------------------
$opcodes = New-Object System.Collections.Generic.List[object]
foreach ($line in Get-Content $opcodesPath) {
    if ($line -match '^\s*([A-Z][A-Z0-9_]*)\s*=\s*(\d+),?\s*$') {
        $opcodes.Add([pscustomobject]@{ Name = $Matches[1]; Value = [int]$Matches[2] })
    }
}
$count = ($opcodes | Where-Object { $_.Name -eq 'NUM_MSG_TYPES' }).Value
if (-not $count) { throw 'NUM_MSG_TYPES no encontrado en Opcodes_1_12_1.h' }
$real = @($opcodes | Where-Object { $_.Name -ne 'NUM_MSG_TYPES' })

$h = $banner + @(
    '#pragma once',
    '',
    '#include "core/Types.h"',
    '',
    'namespace vd::net {',
    '',
    '// World opcodes of 1.12.1 (src/game/Server/Protocol/Opcodes_1_12_1.h). Names kept as in the server.',
    'enum class Opcode : u16 {'
)
foreach ($o in $real) { $h += ('    {0,-40} = {1},' -f $o.Name, $o.Value) }
$h += @(
    '};',
    '',
    "constexpr u32 kOpcodeCount = $count;",
    '',
    '// "SMSG_UPDATE_OBJECT"; "?" for values without a name.',
    'const char* opcodeName(u32 opcode);',
    '',
    '} // namespace vd::net'
)
$cpp = $banner + @(
    '#include "net/Opcodes.gen.h"',
    '',
    'namespace vd::net {',
    'namespace {',
    '',
    'constexpr const char* kNames[kOpcodeCount] = {'
)
$byValue = @{}
foreach ($o in $real) { $byValue[$o.Value] = $o.Name }
for ($v = 0; $v -lt $count; ++$v) {
    if ($byValue.ContainsKey($v)) { $cpp += "    `"$($byValue[$v])`"," } else { $cpp += '    nullptr,' }
}
$cpp += @(
    '};',
    '',
    '} // namespace',
    '',
    'const char* opcodeName(u32 opcode) {',
    '    return opcode < kOpcodeCount && kNames[opcode] ? kNames[opcode] : "?";',
    '}',
    '',
    '} // namespace vd::net'
)
Write-Host "Opcodes: $($real.Count) (NUM_MSG_TYPES = $count)"
Write-Generated 'Opcodes.gen.h' $h
Write-Generated 'Opcodes.gen.cpp' $cpp

# --- Update fields -------------------------------------------------------------------------------------
# Each line: NAME = 0xN | NAME = BASE + 0xN, // 0xABS - Size: S - Type: T - Flags: F
$values = @{}
$groups = New-Object System.Collections.Generic.List[object]
$current = $null
foreach ($line in Get-Content $fieldsPath) {
    if ($line -match '^enum\s+E(\w+)Fields') {
        $current = [pscustomobject]@{ Kind = $Matches[1]; Fields = New-Object System.Collections.Generic.List[object] }
        $groups.Add($current)
        continue
    }
    if ($line -notmatch '^\s*([A-Z][A-Z0-9_]*)\s*=\s*(?:([A-Z][A-Z0-9_]*)\s*\+\s*)?0x([0-9A-Fa-f]+),?\s*(?://(.*))?$') { continue }
    $name = $Matches[1]
    $base = $Matches[2]
    $value = [Convert]::ToInt32($Matches[3], 16)
    $comment = $Matches[4]
    if ($base) {
        if (-not $values.ContainsKey($base)) { throw "Base $base desconocida para $name" }
        $value += $values[$base]
    }
    $values[$name] = $value
    $size = 0; $type = ''
    if ($comment -match '0x([0-9A-Fa-f]+)\s*-\s*Size:\s*(\d+)\s*-\s*Type:\s*(\w+)') {
        if ([Convert]::ToInt32($Matches[1], 16) -ne $value) { throw "Offset del comentario distinto del calculado en $name" }
        $size = [int]$Matches[2]; $type = $Matches[3]
    }
    $current.Fields.Add([pscustomobject]@{ Name = $name; Value = $value; Size = $size; Type = $type })
}

$typeNames = @{ INT = 'Int'; TWO_SHORT = 'TwoShort'; FLOAT = 'Float'; GUID = 'Guid'; BYTES = 'Bytes' }
$h = $banner + @(
    '#pragma once',
    '',
    '#include "core/Types.h"',
    '',
    '#include <span>',
    '',
    '// Update field indices of 1.12.1 (src/game/Objects/UpdateFields_1_12_1.h): positions in the u32 value arrays',
    '// that SMSG_UPDATE_OBJECT fills. Names kept as in the server.',
    'namespace vd::net::uf {',
    ''
)
foreach ($g in $groups) {
    $h += "// $($g.Kind)"
    foreach ($f in $g.Fields) { $h += ('constexpr u16 {0,-44} = 0x{1:X3};' -f $f.Name, $f.Value) }
    $h += ''
}
$h += @(
    'enum class FieldType : u8 { Int, TwoShort, Float, Guid, Bytes };',
    '',
    'struct FieldInfo {',
    '    u16 index;',
    '    u16 size; // in u32 values',
    '    FieldType type;',
    '    const char* name;',
    '};',
    '',
    '// Fields of one object type (only its own block, not the ones it inherits), for debugging and inspectors.',
    'enum class FieldGroup : u8 {'
)
foreach ($g in $groups) { $h += "    $($g.Kind)," }
$h += @(
    '};',
    'std::span<const FieldInfo> fields(FieldGroup group);',
    '',
    '} // namespace vd::net::uf'
)
$cpp = $banner + @(
    '#include "net/UpdateFields.gen.h"',
    '',
    'namespace vd::net::uf {',
    'namespace {',
    ''
)
foreach ($g in $groups) {
    $cpp += "constexpr FieldInfo k$($g.Kind)[] = {"
    foreach ($f in $g.Fields) {
        if ($f.Size -eq 0) { continue } # *_END markers
        $cpp += ('    {{{0}, {1}, FieldType::{2}, "{0}"}},' -f $f.Name, $f.Size, $typeNames[$f.Type])
    }
    $cpp += '};'
}
$cpp += @(
    '',
    '} // namespace',
    '',
    'std::span<const FieldInfo> fields(FieldGroup group) {',
    '    switch (group) {'
)
foreach ($g in $groups) { $cpp += "    case FieldGroup::$($g.Kind): return k$($g.Kind);" }
$cpp += @(
    '    }',
    '    return {};',
    '}',
    '',
    '} // namespace vd::net::uf'
)
foreach ($g in $groups) { Write-Host ("Update fields {0}: {1}" -f $g.Kind, $g.Fields.Count) }
Write-Generated 'UpdateFields.gen.h' $h
Write-Generated 'UpdateFields.gen.cpp' $cpp

# --- Response codes (SMSG_AUTH_RESPONSE, SMSG_CHAR_CREATE...) ----------------------------------------------
$sharedPath = Join-Path $VmangosDir 'src\game\SharedDefines.h'
$inside = $false
$next = 0
$codes = New-Object System.Collections.Generic.List[object]
foreach ($line in Get-Content $sharedPath) {
    if ($line -match '^enum\s+ResponseCodes\b') { $inside = $true; continue }
    if (-not $inside) { continue }
    if ($line -match '^\s*};') { break }
    if ($line -match '^\s*([A-Z][A-Z0-9_]*)\s*(?:=\s*(0x[0-9A-Fa-f]+|\d+))?\s*,?\s*(?://.*)?$') {
        if ($Matches[2]) { $next = [Convert]::ToInt32($Matches[2], $(if ($Matches[2].StartsWith('0x')) { 16 } else { 10 })) }
        $codes.Add([pscustomobject]@{ Name = $Matches[1]; Value = $next })
        ++$next
    }
}
if ($codes.Count -eq 0) { throw 'enum ResponseCodes no encontrado en SharedDefines.h' }
$h = $banner + @(
    '#pragma once',
    '',
    '#include "core/Types.h"',
    '',
    'namespace vd::net {',
    '',
    '// Result codes of SMSG_AUTH_RESPONSE, SMSG_CHAR_CREATE, SMSG_CHARACTER_LOGIN_FAILED... (enum ResponseCodes,',
    '// src/game/SharedDefines.h).',
    'enum class ResponseCode : u8 {'
)
foreach ($c in $codes) { $h += ('    {0,-44} = {1},' -f $c.Name, $c.Value) }
$h += @(
    '};',
    '',
    'const char* responseCodeName(u8 code);',
    '',
    '} // namespace vd::net'
)
$cpp = $banner + @(
    '#include "net/ResponseCodes.gen.h"',
    '',
    'namespace vd::net {',
    '',
    'const char* responseCodeName(u8 code) {',
    '    switch (code) {'
)
foreach ($c in $codes) { $cpp += "    case $($c.Value): return `"$($c.Name)`";" }
$cpp += @(
    '    default: return "?";',
    '    }',
    '}',
    '',
    '} // namespace vd::net'
)
Write-Host "Response codes: $($codes.Count)"
Write-Generated 'ResponseCodes.gen.h' $h
Write-Generated 'ResponseCodes.gen.cpp' $cpp
